/* merge generator chunks into app/data/fourier-font.js */
const fs = require('fs');
const path = require('path');

const dir = process.argv[2];
const outFile = process.argv[3];

const files = fs.readdirSync(dir).filter(f => f.startsWith('chunk-') && f.endsWith('.html'));
const chars = {};
let n = 0;

for (const f of files) {
  const html = fs.readFileSync(path.join(dir, f), 'utf8');
  const m = html.match(/<pre id="out">([\s\S]*?)<\/pre>/);
  if (!m) { console.error('no payload in', f); continue; }
  let payload;
  try { payload = JSON.parse(m[1]); } catch (e) { console.error('bad json in', f, e.message); continue; }
  for (const [k, v] of Object.entries(payload.chars || {})) {
    if (!chars[k]) { chars[k] = v; n++; }
  }
}

const data = {
  v: 1,
  upem: 1000,
  src: 'Noto Sans SC',
  note: 'generated by tools/gen.html — skeleton centreline, rounded corners, spur-pruned',
  chars
};

const body = 'window.EP_FONT=' + JSON.stringify(data) + ';';
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, body, 'utf8');
console.log('chars', n, 'bytes', body.length, '->', outFile);
